import React, { useEffect, useState } from 'react';
import {
  Lightbulb,
  ArrowRight,
  TrendingUp,
  AlertTriangle,
  Scale,
  Calendar,
  CheckCircle2,
  DollarSign,
  Info
} from 'lucide-react';
import { FarmerRecommendation } from '../utils/types.ts';
import { PageId } from '../components/Sidebar.tsx';

interface FarmerRecommendationsPageProps {
  onNavigate: (page: PageId) => void;
}

export default function FarmerRecommendationsPage({ onNavigate }: FarmerRecommendationsPageProps) {
  const [recommendations, setRecommendations] = useState<FarmerRecommendation[]>([]);
  const [loading, setLoading] = useState<boolean>(true);

  useEffect(() => {
    fetch('/api/recommendations')
      .then(res => res.json())
      .then(data => {
        setRecommendations(data);
        setLoading(false);
      })
      .catch(err => {
        console.error(err);
        setLoading(false);
      });
  }, []);

  return (
    <div className="space-y-6">
      {/* Title & Statutory Disclaimer */}
      <div className="p-5 bg-white border border-slate-200 rounded-xl shadow-xs space-y-2">
        <div className="flex items-center gap-2">
          <Lightbulb className="w-5 h-5 text-emerald-700" />
          <h2 className="text-base font-bold text-slate-900">
            Actionable Market Selling Advisories
          </h2>
        </div>
        <p className="text-xs text-slate-600 leading-relaxed">
          These advisories are algorithmically generated by correlating historical AGMARKNET arrival patterns, regional transport costs, and multi-model machine learning price forecasts.
        </p>

        <div className="flex items-start gap-2 p-3 mt-3 rounded-lg bg-amber-50 border border-amber-200/80 text-amber-900 text-xs">
          <Info className="w-4 h-4 text-amber-700 shrink-0 mt-0.5" />
          <div>
            <span className="font-semibold">Notice for Producers:</span> All predicted prices and arbitrage margins are algorithmic statistical estimates. Actual APMC auction prices depend on physical produce quality, daily mandi arrival volumes, and prevailing local trader demand.
          </div>
        </div>
      </div>

      {/* Recommendations Cards Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        {loading ? (
          <div className="col-span-2 py-12 text-center text-slate-400 text-xs">
            Synthesizing market advisories...
          </div>
        ) : (
          recommendations.map(rec => {
            const isHigh = rec.priority === 'high';
            return (
              <div
                key={rec.id}
                className="p-5 bg-white border border-slate-200 rounded-xl shadow-xs flex flex-col justify-between space-y-4 hover:border-emerald-600 transition-colors"
              >
                <div className="space-y-2">
                  <div className="flex items-center justify-between">
                    <span className="text-xs font-bold text-emerald-800 bg-emerald-50 px-2.5 py-0.5 rounded-full border border-emerald-200">
                      {rec.commodity}
                    </span>
                    <span
                      className={`text-[10px] font-bold uppercase tracking-wider px-2 py-0.5 rounded-full ${
                        isHigh
                          ? 'bg-red-50 text-red-700 border border-red-200'
                          : 'bg-slate-100 text-slate-700'
                      }`}
                    >
                      {rec.priority} priority
                    </span>
                  </div>

                  <h3 className="text-sm font-bold text-slate-900">
                    {rec.title}
                  </h3>

                  <p className="text-xs text-slate-600 leading-relaxed">
                    {rec.message}
                  </p>
                </div>

                <div className="pt-3 border-t border-slate-100 space-y-2.5">
                  {rec.potentialGainPerQuintal && (
                    <div className="flex items-center justify-between text-xs bg-emerald-50/60 p-2 rounded-lg">
                      <span className="font-medium text-emerald-900">
                        Estimated Net Upside:
                      </span>
                      <span className="font-extrabold text-emerald-800">
                        +₹{rec.potentialGainPerQuintal} / Quintal
                      </span>
                    </div>
                  )}

                  <div className="text-xs text-slate-800 bg-slate-50 p-2.5 rounded-lg border border-slate-100">
                    <span className="font-semibold text-emerald-900">Recommended Action: </span>
                    {rec.suggestedAction}
                  </div>
                </div>
              </div>
            );
          })
        )}
      </div>

      {/* Quick Navigation Footer */}
      <div className="flex flex-col sm:flex-row items-center justify-between p-4 bg-emerald-900 text-white rounded-xl gap-3">
        <div>
          <div className="text-sm font-bold text-white">
            Need customized market forecasting for your specific mandis?
          </div>
          <div className="text-xs text-emerald-200">
            Run an individualized machine learning prediction or compare live APMC prices.
          </div>
        </div>
        <div className="flex items-center gap-2">
          <button
            onClick={() => onNavigate('prediction')}
            className="px-5 py-2.5 bg-emerald-600 hover:bg-emerald-500 text-white rounded-lg text-xs font-semibold shadow-xs transition-colors"
          >
            Predict Crop Price (Random Forest)
          </button>
        </div>
      </div>
    </div>
  );
}
